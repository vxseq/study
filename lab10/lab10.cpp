#include<iostream>
#include <fstream>      //для чтения файла
#include<string>            //для названия файла 
using namespace std;


//функция для функции базового уровня
void setMin(int& a,int b)
{
    if (b<a)       //проверка что б меньше а 
    {
        a=b;        //если да меняются местами 
    }
    else
    {
        return;         //иначе ничего не меняется
    }
}


//функция для задачи базового уровня
void base()
{
    int a,b;        //объявление переменных
    cout << "Введите два числа" << "\n";        //предложение ввода чисел
    cin >> a >> b;      //ввод чисел
    if (cin.fail())     //проверка ввода
    {
        cin.clear();
        cin.ignore(10000,'\n');
        cout << "Ошибка ввода, введите числа";  //сообщение об ошибке ввода
        return;
    }
    setMin(a,b);        //вызов функции для задачи  
    cout << "Минимальное число " << a << "\n";      //вывод результата
}


//функия для функции среднего уровня
void swapArithmetic(int& a,int& b)
{
    a=a+b;      //суммирую числа для замены местами арифметически
    b=a-b;      //1е число
    a-=b;       //2е число
}


//функция задачи среднего уровня
void medium()
{
    int a,b;            //объвление переменных
    cout << "Введите два числа" << "\n";        //предложение ввода
    cin >> a >> b;                              //ввод
    if (cin.fail())     //проверка ввода
    {
        cin.clear();
        cin.ignore(10000,'\n');
        cout << "Ошибка ввода, введите числа";  //сообщение об ошибке ввода
        return;
    }
    cout << "Ваши числа " << a << " " << b << "\n";     //вывод изначальных чисел
    swapArithmetic(a,b);            //замена чисел арифметически
    cout << "Ваши числа после замены" << a << " " << b << "\n";         //вывод результата
}


//функция для функции повышенного уровня
void readNumbers(const string& filename, int*& arr, int& size)  //константное название файла     ссылка на указатель       ссылка на размер массива
{
    size=0;         //обнуление размера
    ifstream file(filename);        //чтение файла
    if (!file.is_open()) {          //если файл не открылся 
        cout << "Ошибка открытия файла";
        return;
    }
    int number;     //переменная для чисел
    while (file >> number) {        //первый цикл для определения количества элементов
        size++;             //подсчет количества элементов 
    }
    arr=new int[size];        //выделяю память для нового массива с размером size через new 
    file.clear();             //
    file.seekg(0);              // возращение в начало файла 
    int index{0};
    while (file >> number) {      //второй цикл для добавления чисел из файла в массив 
        arr[index]=number;          //присвоение 
        index++;                    //увеличение индекса
    }
    file.close();               //закрытие файла
}


//функция для задачи повышенного уровня 
void advanced()
{
    int* arr = nullptr;         //пустой указатель на первый элемент массива
    int size{0};    //инициализация переменной размера массива
    readNumbers("numbers.txt",arr,size);        //вызов функции 
    cout << "Размер массива = "  << size << "\n";       //вывод размера массива
    cout << "Элементы массива:" << "\n";                //вывод самих элементов 
    for (int i=0;i<size;i++)
    {
        cout << arr[i] << " ";                          //вывод элементов циклом
    }
    delete[] arr;                                       //освобождение памяти
}


int main()
{
    int task_level; //переменная уровня задачи
    cout << "Выберите уровень программы" << "\n" << "1 базовый" << "\n" << "2 средний" << "\n" << "3 повышенный" << "\n"; //предложение выбора уровня задачи
    cin >> task_level; //ввод уровня задачи
    if (cin.fail())     //проверка ввода
    {
        cin.clear();
        cin.ignore(10000,'\n');
        cout << "Ошибка ввода, введите 1 или 2 или 3";  //сообщение об ошибке ввода
        return 0;
    }
    switch(task_level)      //обработка выбора уровня через свитч
    {
        case 1: base();         //базовый
        break;
        case 2: medium();           //средний
        break;
        case 3: advanced();             //повышенный
        break;
        default: 
        cout << "Введен неверный уровень задания, введите 1 или 2 или 3";       //ввели другое
        return 0;
    }
    return 0;
}