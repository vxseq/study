//функция для функции базового уровня
void min(int* a,int* b,int* result)
{
    if (a==nullptr || b==nullptr || result==nullptr)      //проверка указателей
    {
        return;
    }

    if (*a<*b)      //сравнение значений через разыменование указателей
    {
        *result=*a;     //присвоение первого числа результату
    }
    else
    {
        *result=*b;     //присвоение второго числа результату
    }
}


//функция для задачи базового уровня
void base()
{
    int a,b,result{0};      //объявление переменных
    cout << "Введите числа" << "\n";       //предложение ввода
    cin >> a >> b;        //ввод чисел

    if (cin.fail())     //проверка ввода
    {
        cin.clear();
        cin.ignore(10000,'\n');
        cout << "Ошибка ввода, введите числа";       //сообщение об ошибке ввода
        return;
    }

    min(&a,&b,&result);      //вызов функции с передачей адресов переменных
    cout << "Минимальное число = " << result << "\n";       //вывод результата
}


//функция для функции среднего уровня
void shiftLeft(int* arr,int size)
{
    if (arr==nullptr || size<=1)       //проверка указателя и размера массива
    {
        return;
    }

    int first_ans=*arr;       //сохранение значения первого элемента массива

    for (int* p=arr;p<arr+size-1;p++)       //проход по массиву через указатель
    {
        *p=*(p+1);       //присвоение текущему элементу значения следующего
    }

    *(arr+size-1)=first_ans;       //присвоение последнему элементу значения первого
}


//функция для задачи среднего уровня
void medium()
{
    int size;       //переменная размера массива
    cout << "Введите размер массива" << "\n";       //предложение ввода размера
    cin >> size;       //ввод размера массива

    if (cin.fail() || size<=0)       //проверка ввода и размера массива
    {
        cin.clear();
        cin.ignore(10000,'\n');
        cout << "Ошибка ввода, размер массива положительное число";       //сообщение об ошибке ввода
        return;
    }

    int* arr=new int[size];       //выделение памяти для динамического массива

    for (int i=0;i<size;i++)       //цикл для заполнения массива
    {
        *(arr+i)=rand()%100;       //заполнение массива случайными числами через указатель
    }

    cout << "Исходный массив:" << "\n";

    for (int* p=arr;p<arr+size;p++)       //проход по массиву через указатель
    {
        cout << *p << " ";       //вывод значения по адресу указателя
    }

    cout << "\n";

    shiftLeft(arr,size);       //вызов функции для сдвига массива

    cout << "Массив со сдвигом влево на 1 элемент:" << "\n";

    for (int* p=arr;p<arr+size;p++)       //проход по измененному массиву
    {
        cout << *p << " ";       //вывод элементов массива через указатель
    }

    cout << "\n";

    delete[] arr;       //освобождение памяти
}


//функция для задачи повышенного уровня
void advanced()
{
    const int size=10000000;       //размер большого массива
    int* arr=new int[size];       //выделение памяти для массива

    for (int i=0;i<size;i++)       //цикл для заполнения массива
    {
        arr[i]=rand()%100;       //заполнение массива случайными числами
    }

    long long sum1{0},sum2{0};       //переменные для хранения сумм элементов массива

    //обход массива через индексацию
    auto start1=chrono::steady_clock::now();       //запоминаю время начала первого цикла

    for (int i=0;i<size;i++)       //проход по массиву через индексы
    {
        sum1+=arr[i];       //прибавление значения элемента к первой сумме
    }

    auto end1=chrono::steady_clock::now();       //запоминаю время окончания первого цикла


    //обход массива через указатель
    auto start2=chrono::steady_clock::now();       //запоминаю время начала второго цикла

    for (int* p=arr;p<arr+size;p++)       //проход по массиву через изменение адреса указателя
    {
        sum2+=*p;       //прибавление значения по адресу указателя ко второй сумме
    }

    auto end2=chrono::steady_clock::now();       //запоминаю время окончания второго цикла


    //вычисление времени выполнения циклов
    auto time1=chrono::duration_cast<chrono::microseconds>(end1-start1).count();       //время обхода через индексацию в микросекундах
    auto time2=chrono::duration_cast<chrono::microseconds>(end2-start2).count();       //время обхода через указатель в микросекундах

    cout << "Размер массива = " << size << "\n";       //вывод размера массива

    cout << "Сумма через индексацию = " << sum1 << "\n";       //вывод первой суммы
    cout << "Сумма через указатель = " << sum2 << "\n";       //вывод второй суммы

    cout << "Время через индексацию = " << time1 << " мкс" << "\n";       //вывод времени первого цикла
    cout << "Время через указатель = " << time2 << " мкс" << "\n";       //вывод времени второго цикла

    if (time1<time2)       //если время первого цикла меньше
    {
        cout << "Индексация оказалась быстрее" << "\n";
    }
    else if (time2<time1)       //если время второго цикла меньше
    {
        cout << "Указатели оказались быстрее" << "\n";
    }
    else       //если измеренное время выполнения одинаковое
    {
        cout << "Время выполнения одинаковое" << "\n";
    }

    delete[] arr;       //освобождение памяти
}


int main()
{
    srand(static_cast<unsigned>(time(nullptr)));       //для случайных чисел

    int task_level;       //переменная уровня задачи

    cout << "Выберите уровень программы" << "\n"
         << "1 базовый" << "\n"
         << "2 средний" << "\n"
         << "3 повышенный" << "\n";       //предложение выбора уровня задачи

    cin >> task_level;       //ввод уровня задачи

    if (cin.fail())       //проверка ввода
    {
        cin.clear();
        cin.ignore(10000,'\n');
        cout << "Ошибка ввода, введите 1 или 2 или 3";       //сообщение об ошибке ввода
        return 0;
    }

    switch(task_level)       //обработка выбора уровня через свитч
    {
        case 1: base();       //базовый
        break;

        case 2: medium();       //средний
        break;

        case 3: advanced();       //повышенный
        break;

        default:
        cout << "Введен неверный уровень задания";       //ввели другое
        return 0;
    }

    return 0;
}